"""Build a private provisioning bundle; never print keys or place it outside ignored runtime storage."""
import argparse
import io
import json
import re
import shlex
import tarfile
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]


def main():
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--robot-id", required=True)
    parser.add_argument("--keys", type=Path, default=ROOT / ".runtime/robot-keys.json")
    parser.add_argument("--run-id", default="hotspot-live")
    parser.add_argument("--ros-domain", type=int, default=30)
    parser.add_argument("--battery-scale", choices=("fraction", "percent"), default="fraction")
    parser.add_argument("--lidar-model", choices=("LDS-01", "LDS-02", "LDS-03"), required=True)
    args = parser.parse_args()
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_-]{0,47}", args.robot_id):
        parser.error("Invalid robot ID")
    if not re.fullmatch(r"[A-Za-z0-9][A-Za-z0-9_.:-]{0,99}", args.run_id):
        parser.error("Invalid run ID")
    if not 0 <= args.ros_domain <= 232:
        parser.error("ROS domain must be between 0 and 232")
    token = json.loads(args.keys.read_text())[args.robot_id]
    if not isinstance(token, str) or not re.fullmatch(r"[A-Za-z0-9_-]{24,128}", token):
        parser.error("Use a credential generated by swarmlink_data keys")
    configuration = {"SWARMLINK_ROBOT_TOKEN": token, "SWARMLINK_ROBOT_ID": args.robot_id,
                     "SWARMLINK_RUN_ID": args.run_id, "SWARMLINK_BATTERY_SCALE": args.battery_scale,
                     "SWARMLINK_SAMPLE_HZ": "2", "SWARMLINK_MAX_RAYS": "360", "SWARMLINK_ROS_DISTRO": "jazzy",
                     "ROS_DOMAIN_ID": str(args.ros_domain), "TURTLEBOT3_MODEL": "burger", "LDS_MODEL": args.lidar_model}
    output = ROOT / ".runtime" / f"{args.robot_id}-package.tar"
    output.parent.mkdir(exist_ok=True)
    files = ["agents/ros2_agent.py", "swarmlink_data/__init__.py", "swarmlink_data/edge.py", "swarmlink_data/discovery.py"]
    files += [str(p.relative_to(ROOT)).replace("\\", "/") for p in (ROOT / "deployment/robot").iterdir() if p.is_file()]
    with tarfile.open(output, "w") as bundle:
        for name in files:
            bundle.add(ROOT / name, arcname=name)
        data = "".join(f"{name}={shlex.quote(value)}\n" for name, value in configuration.items()).encode()
        entry = tarfile.TarInfo(".runtime/robot.env")
        entry.size, entry.mode = len(data), 0o600
        bundle.addfile(entry, io.BytesIO(data))
    output.chmod(0o600)
    print(f"Created {output.name} in .runtime; it contains a private robot credential. Transfer using SSH/SCP.")


if __name__ == "__main__":
    main()
